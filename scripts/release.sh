#!/bin/bash
# release.sh - runs ON the app server as 'deploy'. Streamed over SSH by Jenkins.
#
# Two slots run the same app side by side as rootless Podman containers:
#   blue  -> 127.0.0.1:5011        green -> 127.0.0.1:5012
# nginx sends public traffic on :8087 to the LIVE slot and serves the IDLE slot on
# 127.0.0.1:8088 (preview, not reachable from outside). Only the root-owned helper
# /usr/local/sbin/bg-switch can move traffic; deploy may run it with "blue" or "green" only.
#
#   status                       show both slots and which one is live
#   stage <image@digest> [0|1]   start the image in the IDLE slot and health-check it there
#                                (1 = simulate a failed check: expect a release that cannot match)
#   staged                       print "<slot> <release>" of the last successful stage
#   preview <slot> <release>     test the staged slot through nginx's preview port
#   switch <slot> <release>      move live traffic to <slot>, counting failed requests meanwhile;
#                                switches back if the new live slot does not answer correctly
#   rollback                     move live traffic back to the idle slot (the previous release,
#                                still running), after checking it is healthy
#   last-switch                  print the result line of the last switch
set -euo pipefail

MODE="${1:?mode: status|stage|staged|preview|switch|rollback|last-switch}"

# Overridable for local testing only
BG_DIR="${BG_DIR:-/etc/nginx/bluegreen}"
SWITCH="${SWITCH:-sudo -n /usr/local/sbin/bg-switch}"
PUBLIC_URL="${PUBLIC_URL:-http://127.0.0.1:8087}"
PREVIEW_URL="${PREVIEW_URL:-http://127.0.0.1:8088}"
PODMAN="${PODMAN:-podman}"
SYSTEMCTL="${SYSTEMCTL:-systemctl --user}"
STATE="${STATE:-$HOME/bluegreen}"
QUADLET_DIR="${QUADLET_DIR:-$HOME/.config/containers/systemd}"
PY="${PYTHON_BIN:-$(command -v python3.11 || command -v python3)}"
export XDG_RUNTIME_DIR="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"

mkdir -p "$STATE" "$QUADLET_DIR"
exec 9>"$STATE/.lock"
flock -w 120 9 || { echo "another release.sh is running"; exit 1; }

port_of()  { case "$1" in blue) echo 5011 ;; green) echo 5012 ;; *) return 1 ;; esac; }
other_of() { case "$1" in blue) echo green ;; green) echo blue ;; *) return 1 ;; esac; }
valid_slot() { case "${1:-}" in blue|green) return 0 ;; *) echo "slot must be blue or green, not '${1:-}'"; exit 2 ;; esac; }

live_slot() {
  local s
  s=$(tr -d '[:space:]' < "$BG_DIR/live" 2>/dev/null || true)
  case "$s" in blue|green) echo "$s" ;; *) echo "cannot read the live slot from $BG_DIR/live (run the setup script)" >&2; return 1 ;; esac
}

slot_info() {  # prints "<release> <image>" recorded for a slot, or nothing
  [ -s "$STATE/$1" ] && cat "$STATE/$1" || true
}

release_of() {  # release label baked into the image by Lab 4
  local r
  r=$($PODMAN image inspect --format '{{index .Labels "org.opencontainers.image.version"}}' "$1" 2>/dev/null || true)
  [ -n "$r" ] && [ "$r" != "<no value>" ] && echo "$r"
}

# check <url> <expected release> [expected X-Slot header] [attempts]
# Passes when /health says status=ok with that release (and nginx's X-Slot header matches).
check() {
  local url="$1" want="$2" slot="${3:-}" tries="${4:-15}" i hdr body got_slot
  hdr=$(mktemp); body=$(mktemp)
  for ((i = 1; i <= tries; i++)); do
    if curl -sS -m 3 -D "$hdr" -o "$body" "$url/health" 2>/dev/null; then
      got_slot=$(tr -d '\r' < "$hdr" | awk -F': *' 'tolower($1) == "x-slot" { print $2 }' | tail -1)
      if [ -z "$slot" ] || [ "$got_slot" = "$slot" ]; then
        if "$PY" -c '
import json, sys
try:
    d = json.load(open(sys.argv[1]))
except (ValueError, OSError):
    sys.exit(1)
sys.exit(0 if d.get("status") == "ok" and d.get("release") == sys.argv[2] else 1)
' "$body" "$want"; then
          echo "  ok on attempt $i: $(cat "$body")${slot:+ (X-Slot: $got_slot)}"
          rm -f "$hdr" "$body"
          return 0
        fi
      fi
    fi
    sleep 1
  done
  echo "  FAILED after $tries attempts: expected release '$want'${slot:+ from slot $slot}; last response: $(cat "$body" 2>/dev/null || true)${slot:+ (X-Slot: ${got_slot:-none})}"
  rm -f "$hdr" "$body"
  return 1
}

render_unit() {  # render_unit <slot> <image@digest>
  local slot="$1" port
  port=$(port_of "$slot")
  cat > "$QUADLET_DIR/bg-$slot.container.tmp" <<EOF
# Generated by release.sh (Lab 7) - do not edit by hand
[Unit]
Description=Lab 7 - Inventory API, $slot slot (rootless Podman)
Wants=network-online.target
After=network-online.target

[Container]
ContainerName=bg-$slot
Image=$2
Pull=never
PublishPort=127.0.0.1:$port:8000
ReadOnly=true
Tmpfs=/tmp
DropCapability=ALL
NoNewPrivileges=true
PodmanArgs=--memory=256m --pids-limit=128
Label=lab=blue-green-nginx-deploy
Label=slot=$slot

[Service]
Restart=on-failure
TimeoutStartSec=90

[Install]
WantedBy=default.target
EOF
  mv "$QUADLET_DIR/bg-$slot.container.tmp" "$QUADLET_DIR/bg-$slot.container"
  $SYSTEMCTL daemon-reload
}

clear_slot() {  # stop a slot and remove its unit so it does not come back at boot
  $SYSTEMCTL stop "bg-$1.service" 2>/dev/null || true
  rm -f "$QUADLET_DIR/bg-$1.container" "$STATE/$1"
  $SYSTEMCTL daemon-reload
}

show_status() {
  local live s info state
  live=$(live_slot)
  echo "live slot: $live (public :8087)   idle slot: $(other_of "$live") (preview 127.0.0.1:8088)"
  for s in blue green; do
    info=$(slot_info "$s")
    state=$($SYSTEMCTL is-active "bg-$s.service" 2>/dev/null || true)
    printf '  %-5s %-5s 127.0.0.1:%s  %-9s %s\n' "$s" "$([ "$s" = "$live" ] && echo LIVE || echo idle)" \
      "$(port_of "$s")" "${state:-inactive}" "${info:-(empty)}"
  done
}

# do_switch <slot> <release>: shared by switch and rollback
do_switch() {
  local to="$1" rel="$2" from probe_out stop t0 t1 total failed result
  from=$(live_slot)
  [ "$to" != "$from" ] || { echo "$to is already live"; exit 1; }

  echo "pre-check: $to answers directly with $rel"
  check "http://127.0.0.1:$(port_of "$to")" "$rel" "" 5 || { echo "refusing to switch: $to is not healthy"; exit 1; }

  # Count every response on the public port while traffic moves (only if something was live)
  probe_out=$(mktemp); stop="$probe_out.stop"
  if [ -n "$(slot_info "$from")" ]; then
    ( while [ ! -e "$stop" ]; do
        curl -s -o /dev/null -m 2 -w '%{http_code}\n' "$PUBLIC_URL/health" >> "$probe_out" 2>/dev/null || true
      done ) &
    sleep 1
  fi

  echo "switching live traffic: $from -> $to"
  t0=$(date +%s.%N)
  if ! $SWITCH "$to"; then
    touch "$stop"; wait || true; rm -f "$probe_out" "$stop"
    echo "bg-switch failed: live traffic stays on $from"
    exit 1
  fi

  echo "verify: public :8087 serves $rel from $to"
  if ! check "$PUBLIC_URL" "$rel" "$to" 15; then
    echo "switching BACK to $from"
    $SWITCH "$from" || echo "WARNING: switch back failed - check nginx now"
    touch "$stop"; wait || true; rm -f "$probe_out" "$stop"
    exit 1
  fi
  t1=$(date +%s.%N)

  sleep 2   # keep counting for a moment after the switch
  touch "$stop"; wait || true
  if [ -s "$probe_out" ]; then
    total=$(wc -l < "$probe_out")
    failed=$(grep -vc '^200$' "$probe_out" || true)
    result="requests=$total failed=$failed"
  else
    result="requests=0 failed=0 (first release: nothing was live)"
  fi
  rm -f "$probe_out" "$stop"
  result="from=$from to=$to release=$rel switch_seconds=$(awk -v a="$t0" -v b="$t1" 'BEGIN { printf "%.1f", b - a }') $result"
  echo "$result" > "$STATE/last-switch"
  echo "SWITCH $result"
  if [ -n "$(slot_info "$from")" ]; then
    echo "live: $to ($rel); $from keeps running $(slot_info "$from" | cut -d' ' -f1) for instant rollback"
  else
    echo "live: $to ($rel); $from is empty, so there is no rollback target yet"
  fi
}

case "$MODE" in
  status)
    show_status
    ;;

  stage)
    IMAGE="${2:?image@digest}"
    SIMULATE="${3:-0}"
    $PODMAN image exists "$IMAGE" || { echo "image is not present locally: $IMAGE"; exit 1; }
    RELEASE=$(release_of "$IMAGE") || { echo "image has no org.opencontainers.image.version label"; exit 1; }
    LIVE=$(live_slot); IDLE=$(other_of "$LIVE")
    echo "image:   ${IMAGE##*@}"
    echo "release: $RELEASE (from the image label)"
    echo "staging into the IDLE slot: $IDLE (127.0.0.1:$(port_of "$IDLE")); live slot $LIVE is not touched"
    if [ -n "$(slot_info "$IDLE")" ]; then
      echo "  replacing $(slot_info "$IDLE" | cut -d' ' -f1) in $IDLE"
    fi
    rm -f "$STATE/staged"

    EXPECT="$RELEASE"
    if [ "$SIMULATE" = "1" ]; then
      EXPECT="$RELEASE-simulated-mismatch"
      echo "SIMULATED FAILURE: the check will expect '$EXPECT'"
    fi

    render_unit "$IDLE" "$IMAGE"
    $SYSTEMCTL restart "bg-$IDLE.service" || true
    echo "health check on $IDLE:"
    if check "http://127.0.0.1:$(port_of "$IDLE")" "$EXPECT" "" 15; then
      echo "$RELEASE $IMAGE" > "$STATE/$IDLE"
      echo "$IDLE $RELEASE" > "$STATE/staged"
      echo "STAGED $IDLE $RELEASE"
    else
      echo "UNHEALTHY: $RELEASE in $IDLE - recent log:"
      $PODMAN logs --tail 20 "bg-$IDLE" 2>/dev/null || true
      clear_slot "$IDLE"
      echo "$IDLE stopped and cleared; live traffic never left $LIVE"
      exit 1
    fi
    ;;

  staged)
    [ -s "$STATE/staged" ] && cat "$STATE/staged" || true
    ;;

  preview)
    SLOT="${2:?slot}"; REL="${3:?release}"
    valid_slot "$SLOT"
    [ "$SLOT" != "$(live_slot)" ] || { echo "$SLOT is live, not idle"; exit 1; }
    echo "preview port serves $SLOT:"
    check "$PREVIEW_URL" "$REL" "$SLOT" 5
    echo "API through the preview port:"
    out=$(curl -fsS -m 5 "$PREVIEW_URL/api/items?category=network")
    echo "  $out"
    printf '%s' "$out" | grep -q '"count":' || { echo "preview API test failed"; exit 1; }
    echo "preview passed"
    ;;

  switch)
    SLOT="${2:?slot}"; REL="${3:?release}"
    valid_slot "$SLOT"
    do_switch "$SLOT" "$REL"
    ;;

  rollback)
    LIVE=$(live_slot); IDLE=$(other_of "$LIVE")
    INFO=$(slot_info "$IDLE")
    [ -n "$INFO" ] || { echo "nothing to roll back to: the idle slot ($IDLE) is empty"; exit 1; }
    echo "rollback: $LIVE ($(slot_info "$LIVE" | cut -d' ' -f1)) -> $IDLE (${INFO%% *}), already running"
    do_switch "$IDLE" "${INFO%% *}"
    ;;

  last-switch)
    [ -s "$STATE/last-switch" ] && cat "$STATE/last-switch" || true
    ;;

  *)
    echo "usage: release.sh status|stage|staged|preview|switch|rollback|last-switch ..."
    exit 2
    ;;
esac
